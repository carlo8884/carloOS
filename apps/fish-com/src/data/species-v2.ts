export type SpeciesCategory =
  | 'freshwater-fish'
  | 'saltwater-fish'
  | 'freshwater-invert'
  | 'saltwater-invert'

export type CareLevel = 'beginner' | 'intermediate' | 'advanced'
export type Temperament = 'peaceful' | 'semi-aggressive' | 'aggressive'
export type Diet = 'herbivore' | 'omnivore' | 'carnivore' | 'detritivore'

export type AffiliateVendor =
  | 'amazon'
  | 'chewy'
  | 'bulkreefsupply'
  | 'liveaquaria'
  | 'marinedepot'

export interface ProductRecommendation {
  /** e.g. 'food', 'tank', 'filter', 'heater', 'lighting', 'water-test', 'substrate', 'plants', 'decor', 'supplement' */
  category: string
  vendor: AffiliateVendor
  /** Amazon ASIN, Chewy product slug, BRS SKU, or descriptive search term */
  sku: string
  /** Human-readable label shown on the CTA */
  label: string
}

export interface SpeciesProfile {
  slug: string
  commonName: string
  scientificName: string
  category: SpeciesCategory
  care_level: CareLevel
  max_size_inches: number
  lifespan_years: [number, number]
  tank_size_min_gallons: number
  temperature_f: [number, number]
  ph: [number, number]
  water_hardness_dgh?: [number, number]
  salinity_sg?: [number, number]
  temperament: Temperament
  schooling: boolean
  /** Min number per group when schooling = true */
  schooling_min?: number
  diet: Diet
  tankmate_compatibility: string[]
  /** Slugs of 2–3 compatible tankmate species for cross-linking. */
  tankmate_slugs: string[]
  common_diseases: string[]
  recommended_products: ProductRecommendation[]
  care_tips: string[]
  common_mistakes: string[]
  /** 4–5 species-specific FAQs for the page accordion. */
  faqs: Array<{ question: string; answer: string }>
  /** Short summary string used by metadata + hero subtitle. */
  summary: string
}

