/**
 * Helpers consumed by the [slug] template and the /brands index.
 */
export function getBrandBySlug(slug: string): Brand | undefined {
  return Brands.find((b) => b.slug === slug)
}

export function getRelatedBrandsByPriceTier(slug: string, limit = 4): Brand[] {
  const brand = getBrandBySlug(slug)
  if (!brand) return []
  return Brands.filter(
    (b) => b.slug !== slug && b.priceTier === brand.priceTier
  ).slice(0, limit)
}
