/**
 * Dog.com — Disease & condition data file.
 *
 * Programmatic SEO source-of-truth for /health/[slug] template.
 * Each entry must be sourced from ACVIM consensus statements, JAVMA,
 * Morris Animal Foundation, OFA, ACVD, AAHA, VCA Animal Hospitals,
 * Merck Veterinary Manual, or peer-reviewed veterinary literature.
 *
 * IMPORTANT — sourcing rules:
 *   - Symptoms, diagnostic approaches, and treatment tiers must reflect
 *     current standard-of-care references — not invented protocols.
 *   - We never fabricate prevalence percentages. Prevalence is a categorical
 *     field ('Common' | 'Moderate' | 'Rare') based on published incidence.
 *   - Breed predispositions are listed only when documented in OFA / breed
 *     club CHIC panels / Morris Animal Foundation / peer-reviewed studies.
 *   - If a field is unknown, leave it undefined and the template will omit it.
 *
 * Existing canonical hand-written pages on /health/ (dog-allergies, parvovirus
 * if present, etc.) are flagged with existingHandWrittenSlug: true and
 * excluded from generateStaticParams.
 */

export type DiseaseCategory =
  | 'Infectious'
  | 'Genetic'
  | 'Behavioral'
  | 'Dental'
  | 'Endocrine'
  | 'Skin'
  | 'Cardiac'
  | 'Renal'
  | 'GI'
  | 'Oncology'
  | 'Orthopedic'
  | 'Neurological'
  | 'Ocular'
  | 'Respiratory'
  | 'Reproductive'

export type Urgency =
  | 'Emergency — ER now'
  | 'Same-day vet'
  | 'Schedule vet visit'
  | 'Monitor at home'

export type Prevalence = 'Common' | 'Moderate' | 'Rare'

export type AgeOnset =
  | 'Puppy (<12mo)'
  | 'Young adult (1-3y)'
  | 'Adult (3-7y)'
  | 'Senior (7+)'
  | 'Any age'

