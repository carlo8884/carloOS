/**
 * Slugs that will be rendered by the dynamic /health/[slug] template.
 * Excludes any entry where either:
 *   - existingHandWrittenSlug is true, OR
 *   - The slug appears in EXISTING_STATIC_HEALTH_SLUGS (defensive — avoids
 *     Next.js route collision if a static folder already exists for the slug).
 */
export function getProgrammaticDiseases(): Disease[] {
  return Diseases.filter(
    (d) => !d.existingHandWrittenSlug && !EXISTING_STATIC_HEALTH_SLUGS.has(d.slug),
  )
}
