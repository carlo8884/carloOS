export function getMeeting(slugOrId: string): Meeting | undefined {
  return meetings.find((m) => m.id === slugOrId || m.courseSlug === slugOrId);
}

export function getRace(raceId: string) {
  for (const m of meetings) {
    const race = m.races.find((r) => r.id === raceId);
    if (race) return { meeting: m, race };
  }
  return null;
}

export function allRaces() {
  return meetings.flatMap((m) => m.races.map((race) => ({ meeting: m, race })));
}
